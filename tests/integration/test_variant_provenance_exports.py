MULTI = "parse_rows() raises KeyError.\n\nSee DataLoader for details.\n\nIt worked before."
SINGLE = "load_config() ignores the env var CONFIG_PATH."
PARAPHRASE_V = Paraphrase.transform_version
EXCLUSION_REASONS = {
    ("org__a-1", "original"): "",
    ("org__a-1", "paraphrase"): "",
    ("org__a-1", "reordering"): "",
    ("org__b-2", "original"): "",
    ("org__b-2", "paraphrase"): "",
    ("org__b-2", "reordering"): NOOP_REASON,
}
PROVENANCE = {
    ("org__a-1", "original"): ("original", None, None, False),
    ("org__a-1", "paraphrase"): (TRANSFORMATION_MODEL, PARAPHRASE_V, "real", False),
    ("org__a-1", "reordering"): ("deterministic", "2", "real", False),
    ("org__b-2", "original"): ("original", None, None, False),
    ("org__b-2", "paraphrase"): (TRANSFORMATION_MODEL, PARAPHRASE_V, "real", False),
    ("org__b-2", "reordering"): ("deterministic", "2", "real", True),  # single paragraph
}


class FakeAnthropic:
    def __init__(self, **_kwargs):
        self.messages = SimpleNamespace(create=self._create)

    @staticmethod
    def _create(**kwargs):
        if kwargs["model"] == TRANSFORMATION_MODEL:
            text = json.dumps({"transformed_text": "Restated: " + kwargs["messages"][0]["content"],
                               "transformation_notes": "fake"})
        else:
            text = "```diff\n--- a/pkg/x.py\n+++ b/pkg/x.py\n@@ -1 +1 @@\n-a\n+b\n```"
        return SimpleNamespace(content=[SimpleNamespace(type="text", text=text)],
                               usage=SimpleNamespace(input_tokens=5, output_tokens=5),
                               stop_reason="end_turn")


@pytest.fixture()
def experiment(tmp_path, monkeypatch, no_network):
    monkeypatch.setattr(anthropic, "Anthropic", FakeAnthropic)
    engine = create_engine(f"sqlite:///{tmp_path / 'exports.db'}")
    Base.metadata.create_all(engine)
    Session = sessionmaker(bind=engine)
    monkeypatch.setattr(dashboard_db, "_session", lambda: Session())
    with Session() as db:
        db.add_all([
            Issue(external_id="org__a-1", repo_name="org/a", source="swebench_lite",
                  issue_text=MULTI),
            Issue(external_id="org__b-2", repo_name="org/b", source="swebench_lite",
                  issue_text=SINGLE),
        ])
        db.commit()
        config = ExperimentConfig(
            experiment_name="provenance",
            execution_mode="real",
            agents=[AgentConfig(name="llm_baseline")],
            issues=IssueConfig(issue_ids=["org__a-1", "org__b-2"]),
            transformations=[TransformationConfig(name="paraphrase"),
                             TransformationConfig(name="reordering", params={"seed": 1})],
            cost_limit_usd=1.0,
        )
        exp = ExperimentRunner(config, db).run()
        MetricsEngine().compute(exp.id, db)
        db.commit()
        experiment_id = exp.id
    yield Session, experiment_id
    engine.dispose()


def _cell(row) -> tuple[str, str]:
    return row["issue_id"], row["transformation_name"]


def _provenance(row) -> tuple:
    version = row["transform_version"] or None
    mode = row["generation_mode"] or None
    noop = row["noop"] in (True, "True", "true")
    return row["generator"], version, mode, noop


def test_no_op_variants_are_excluded_from_sc_and_ts_and_counted(experiment):
    Session, experiment_id = experiment
    with Session() as db:
        metrics = db.query(Metric).filter_by(experiment_id=experiment_id).all()
        rows = [(m.scope, m.scope_key, m.metric_name, m.metric_value) for m in metrics]
    counts = exclusion_counts(rows)
    assert counts["noop"] == 1
    assert counts["noop_by_transformation"] == {"paraphrase": 0, "reordering": 1}
    ts = {m.scope_key: m.metric_value for m in metrics
          if m.metric_name == "transformation_sensitivity"}
    assert set(ts) == {"llm_baseline|paraphrase", "llm_baseline|reordering"}
    sc_b = [m.metric_value for m in metrics
            if m.metric_name == "success_consistency" and m.scope_key == "llm_baseline|org__b-2"]
    assert sc_b == [1.0]  # computed from paraphrase only: the no-op reordering is left out
    outcome_runs = {m.scope_key for m in metrics if m.metric_name == "outcome"}
    assert len(outcome_runs) == 5  # 6 runs, the no-op one has no outcome


def test_cli_exports_carry_the_provenance(experiment, tmp_path):
    Session, experiment_id = experiment
    with Session() as db:
        exp = db.get(Experiment, experiment_id)
        runs_csv, _ = CSVExporter().export(exp, tmp_path / "csv", db)
        json_path = JSONExporter().export(exp, tmp_path / "json", db)
        report = ReportGenerator().export(exp, tmp_path / "md", db).read_text(encoding="utf-8")

    with open(runs_csv, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    assert {_cell(r): _provenance(r) for r in rows} == PROVENANCE
    assert {_cell(r): r["exclusion_reason"] for r in rows} == EXCLUSION_REASONS

    exported = json.loads(json_path.read_text(encoding="utf-8"))
    assert {_cell(r): _provenance(r) for r in exported["runs"]} == PROVENANCE
    assert {_cell(r): r["exclusion_reason"] or "" for r in exported["runs"]} == EXCLUSION_REASONS
    assert exported["exclusions"]["noop_by_transformation"] == {"paraphrase": 0, "reordering": 1}

    assert "## Variant Provenance" in report
    assert f"| org__a-1 | paraphrase | {TRANSFORMATION_MODEL} | {PARAPHRASE_V} | real | no | no |" in report
    assert (
        "| org__b-2 | reordering | deterministic | 2 | real | yes | no | "
        f"{NOOP_REASON} |" in report
    )
    assert "  - reordering: 1" in report


def test_dashboard_shows_and_exports_the_provenance(experiment):
    Session, experiment_id = experiment
    runs_df = attach_outcomes(dashboard_db.load_runs_df(experiment_id),
                              dashboard_db.load_metrics_df(experiment_id))

    exported = list(csv.DictReader(io.StringIO(runs_csv_bytes(runs_df).decode())))
    assert {_cell(r): _provenance(r) for r in exported} == PROVENANCE
    assert {_cell(r): r["exclusion_reason"] for r in exported} == EXCLUSION_REASONS
    assert {(r["issue_id"], r["transformation_name"]): r["exclusion_reason"]
            for r in provenance_rows(runs_df)}[("org__b-2", "reordering")] == NOOP_REASON

    assert {(r["issue_id"], r["transformation_name"]): (r["generator"], r["noop"])
            for r in provenance_rows(runs_df)} == {
        ("org__a-1", "paraphrase"): (TRANSFORMATION_MODEL, False),
        ("org__a-1", "reordering"): ("deterministic", False),
        ("org__b-2", "paraphrase"): (TRANSFORMATION_MODEL, False),
        ("org__b-2", "reordering"): ("deterministic", True),
    }
    rows = {row["Transformation"]: row for row in rq1_table_rows(runs_df, "org__b-2")}
    assert rows["Reordering"]["Outcome"] == "Excluded (no-op variant)"

    with Session() as db:
        metrics = db.query(Metric).filter_by(experiment_id=experiment_id).all()
        counts = exclusion_counts([(m.scope, m.scope_key, m.metric_name, m.metric_value)
                                   for m in metrics])
    assert "1 run(s) on no-op variants (identical to the original) (Reordering: 1)" in (
        exclusions_text(counts)
    )
